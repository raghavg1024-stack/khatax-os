import {test} from "node:test";
import assert from "node:assert/strict";
import {mkdirSync} from "node:fs";
import {resolve} from "node:path";
import {spawnSync} from "node:child_process";
mkdirSync("test-results",{recursive:true});
process.env.DATABASE_URL=`file:${resolve("test-results",`business-${Date.now()}.db`).replaceAll("\\","/")}`;
process.env.TURSO_DATABASE_URL="";process.env.TURSO_AUTH_TOKEN="";process.env.VERCEL="";
const migrated=spawnSync(process.execPath,["node_modules/prisma/build/index.js","migrate","deploy"],{env:process.env,encoding:"utf8"});
assert.equal(migrated.status,0,migrated.stderr);
const {db}=await import("../src/lib/db");
const {businessMutation,lineTotal}=await import("../src/lib/business");
const {indiaDate}=await import("../src/lib/shared");
test("business records atomically connect supplier stock sales credit cash and idempotency",async()=>{
 try{
  assert.equal(lineTotal(1500,20000),30000);
  assert.throws(()=>lineTotal(1,1),/fractional paise/);
  const common={acknowledge:true};
  const customer=await db.customer.create({data:{name:"Stock Customer"}});
  const productInput={...common,op:"product",key:"product-test-001",name:"Rice bag",pricePaise:20000,unit:"bag",initialStockMilli:1000};
  const p=await businessMutation(productInput);
  const product=(p as {product:{id:string}}).product;
  assert.equal((await businessMutation(productInput)).idempotent,true);
  await assert.rejects(()=>businessMutation({...productInput,pricePaise:22000}),/different details/);
  assert.equal(await db.product.count(),1);
  const supplier=(await businessMutation({...common,op:"supplier",key:"supplier-test-001",name:"Test distributor"}) as {supplier:{id:string}}).supplier;
  const receive={...common,op:"receive",key:"invoice-test-001",supplierId:supplier.id,reference:"INV-1",occurredOn:indiaDate(),dueOn:indiaDate(),lines:[{productId:product.id,quantityMilli:2000,unitPricePaise:15000}],taxPaise:1000,totalPaise:31000};
  await businessMutation(receive);
  await assert.rejects(()=>businessMutation({...receive,key:"invoice-duplicate-lines",reference:"INV-DUP",lines:[receive.lines[0],receive.lines[0]]}),/duplicate product/);
  assert.equal((await db.product.findUniqueOrThrow({where:{id:product.id}})).stockMilli,3000);
  await businessMutation(receive);
  assert.equal((await db.product.findUniqueOrThrow({where:{id:product.id}})).stockMilli,3000);
  await assert.rejects(()=>businessMutation({...receive,key:"invoice-test-duplicate"}),/already been recorded/);
  await assert.rejects(()=>businessMutation({...receive,key:"invoice-test-bad",reference:"INV-2",totalPaise:30000}),/do not match/);
  assert.equal(await db.supplierInvoice.count(),1);
  const sale={...common,op:"sale",key:"sale-test-001",customerId:customer.id,mode:"credit",occurredOn:indiaDate(),lines:[{productId:product.id,quantityMilli:1500}],expectedTotalPaise:30000};
  await businessMutation(sale);
  await businessMutation(sale);
  assert.equal(await db.sale.count(),1);assert.equal(await db.entry.count(),1);
  assert.equal((await db.entry.findFirstOrThrow()).amountPaise,30000);
  assert.equal((await db.product.findUniqueOrThrow({where:{id:product.id}})).stockMilli,1500);
  await assert.rejects(()=>businessMutation({...sale,key:"sale-test-insufficient",lines:[{productId:product.id,quantityMilli:2000}],expectedTotalPaise:40000}),/Not enough stock/);
  await assert.rejects(()=>businessMutation({...sale,key:"sale-test-stale",expectedTotalPaise:10000}),/price changed/);
  assert.equal(await db.entry.count(),1,"Failed sale rolls back financial entry");
  await businessMutation({...sale,key:"sale-test-cash",mode:"cash",lines:[{productId:product.id,quantityMilli:1000}],expectedTotalPaise:20000});
  assert.equal(await db.entry.count(),1,"Cash sale does not add customer debt");
  assert.equal((await db.cashRecord.findFirstOrThrow({where:{kind:"receipt"}})).amountPaise,20000);
  await businessMutation({...common,op:"supplierPayment",key:"supplier-pay-test",supplierId:supplier.id,amountPaise:10000,occurredOn:indiaDate()});
  assert.equal((await db.cashRecord.findFirstOrThrow({where:{kind:"expense"}})).amountPaise,10000);
  await assert.rejects(()=>businessMutation({...common,op:"supplierPayment",key:"supplier-pay-too-much",supplierId:supplier.id,amountPaise:22000,occurredOn:indiaDate()}),/exceeds/);
  const invoice=await db.supplierInvoice.findFirstOrThrow();
  await assert.rejects(()=>db.supplierInvoice.update({where:{id:invoice.id},data:{totalPaise:1}}));
  const movement=await db.inventoryMovement.findFirstOrThrow();
  await assert.rejects(()=>db.inventoryMovement.delete({where:{id:movement.id}}));
  await assert.rejects(()=>businessMutation({...productInput,key:"ack-test-missing",acknowledge:false}));
  assert.ok(await db.audit.count()>=6);
 }finally{await db.$disconnect();}
});
